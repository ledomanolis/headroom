# Downloads the latest UK nominal gilt zero coupon yields from the Bank of England
# and writes them to data/market-data.js for the app to read.
# Run from anywhere:  powershell -ExecutionPolicy Bypass -File tools\update-market-data.ps1

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$out = Join-Path $root 'data\market-data.js'

# Bank of England yield curve series: nominal zero coupon yields at 5, 10 and 20 years.
$series = [ordered]@{ 5 = 'IUDSNZC'; 10 = 'IUDMNZC'; 20 = 'IUDLNZC' }

$from = (Get-Date).AddDays(-30).ToString('dd/MMM/yyyy', [Globalization.CultureInfo]::InvariantCulture)
$url = 'https://www.bankofengland.co.uk/boeapps/database/_iadb-fromshowcolumns.asp?csv.x=yes' +
  "&Datefrom=$from&Dateto=now&SeriesCodes=$($series.Values -join ',')&CSVF=TN&UsingCodes=Y&VPD=Y&VFD=N"

$response = Invoke-WebRequest $url -UseBasicParsing -TimeoutSec 30 -UserAgent 'Mozilla/5.0'
$rows = [Text.Encoding]::UTF8.GetString($response.Content).Trim() -split "`r?`n" | ConvertFrom-Csv

# Latest date with a value for every tenor.
$latest = $rows | Where-Object {
  $row = $_
  -not ($series.Values | Where-Object { [string]::IsNullOrWhiteSpace($row.$_) })
} | Select-Object -Last 1
if (-not $latest) { throw 'No complete row of yields found in the Bank of England download.' }

$asAt = [DateTime]::ParseExact($latest.DATE, 'dd MMM yyyy', [Globalization.CultureInfo]::InvariantCulture)
$curve = ($series.GetEnumerator() | ForEach-Object {
  $yield = [double]$latest.($_.Value) / 100
  "      { term: $($_.Key), yield: $($yield.ToString([Globalization.CultureInfo]::InvariantCulture)) }"
}) -join ",`n"

$js = @"
// Generated by tools/update-market-data.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm'). Do not edit by hand.
window.HEADROOM_MARKET = {
  source: 'Bank of England, nominal gilt zero coupon yields ($($series.Values -join ', '))',
  asAt: '$($asAt.ToString('yyyy-MM-dd'))',
  giltCurve: [
$curve
  ]
};
"@

New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
[IO.File]::WriteAllText($out, $js + "`n", (New-Object System.Text.UTF8Encoding $false))
Write-Host "Wrote gilt yields as at $($asAt.ToString('d MMM yyyy')) to $out"
